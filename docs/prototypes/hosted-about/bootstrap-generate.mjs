/** Generates prototype-only SQL. Never opens a database or reads environment files. */
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
const here = dirname(fileURLToPath(import.meta.url));
const web = process.argv[2];
if (!web) throw new Error("Provide the pinned Web checkout path");
const hash = s => createHash("sha256").update(s).digest("hex");
const raw = readFileSync(resolve(here, "fresh-schema.candidate.sql"), "utf8");
if (hash(raw) !== "e123ad7bdd125c8aed597400c9e6101e6c46b1997d72248538bbf0513a8c5b5b")
  throw new Error("Pinned schema candidate changed; review generator inputs");
let sql = raw.replace(/^--.*\n/gm, "");
for (const [before, after] of [
  ['"added_by" timestamptz_ops', '"added_by" uuid_ops'],
  ['"user_id" timestamp_ops', '"user_id" uuid_ops'],
]) {
  if (sql.split(before).length !== 2) throw new Error(`Expected exactly one ${before}`);
  sql = sql.replace(before, after);
}
// PG17 built-in v4 UUID replaces uuid-ossp-only default spelling, not data.
sql = sql.replaceAll("uuid_generate_v4()", "gen_random_uuid()");
sql =
  "-- ISOLATED EMPTY DATABASE ONLY. Reviewed bootstrap transformations; no historical migration replay.\nCREATE SCHEMA musicnerd_private;\nCREATE EXTENSION pg_trgm WITH SCHEMA public;\n" +
  sql;
const expectedInputs = {
  "0064_lore_activity_lock.sql": "3b2ec181364f3f414ee9f73a920716546fec3c68b23a62c3cc22386ee652b0e0",
  "0035_account_merge_attribution.sql":
    "ce893158ed3b9dc0fcfbe27151789fdf48b5a5628c1ded6edd9f4a97282e17e8",
  "0039_source_versions.sql": "da4951de87e9262f1c40cd890916263fba31da61fc2016c33695b6ced57703cf",
  "0056_catalog_disconnect.sql": "72a33d1eec6333585dc0ac2312569a14dbbec7d8475beddc9573a60d3cfc02b2",
  "0058_catalog_automatic_reconnect_guard.sql":
    "3fb63c4db1653612ee144fba84275a8a25b84227f1bcb9d51817914fe5c55adb",
  "0059_catalog_counterpart_jobs.sql":
    "3489c2af1f763197ebb28df012c9d310c938a00d0b5d54c45bd9768b831cc99e",
  "0063_legacy_bio_publications.sql":
    "3a8ba693b10d4a45017f19ffd94643d885d547f1eeac7ee3e65e33f1d5bc88eb",
};
const files = [
  "0035_account_merge_attribution",
  "0039_source_versions",
  "0056_catalog_disconnect",
  "0058_catalog_automatic_reconnect_guard",
  "0059_catalog_counterpart_jobs",
  "0063_legacy_bio_publications",
  "0064_lore_activity_lock",
];
const manifest = {
  webCommit: "d219118f1e3b9a0fa5c3807a8bf3ea4414fad99f",
  candidateSha256: hash(raw),
  inputs: [],
  functions: [],
  triggers: [],
};
let supplemental =
  "-- SQL-only functions/triggers and function ACLs copied verbatim from pinned migrations.\n";
for (const name of files) {
  const text = readFileSync(resolve(web, "drizzle", name + ".sql"), "utf8");
  if (hash(text) !== expectedInputs[name + ".sql"])
    throw new Error("Pinned migration changed: " + name);
  manifest.inputs.push({ file: name + ".sql", sha256: hash(text) });
  const definitions = [
    ...text.matchAll(/^CREATE FUNCTION [\s\S]*?\$\$;/gm),
    ...text.matchAll(/^CREATE TRIGGER [\s\S]*?;/gm),
    ...text.matchAll(/^(?:REVOKE|GRANT) [^;\n]* ON FUNCTION [\s\S]*?;/gm),
  ];
  // Match function grants that start GRANT EXECUTE ON FUNCTION; no table/role grants imported.
  const ordered = definitions.sort((a, b) => a.index - b.index);
  supplemental +=
    "\n-- " +
    name +
    "\n" +
    (name === "0064_lore_activity_lock" ? text : ordered.map(m => m[0]).join("\n")) +
    "\n";
  manifest.functions.push(...[...text.matchAll(/^CREATE FUNCTION ([^(]+)/gm)].map(m => m[1]));
  manifest.triggers.push(...[...text.matchAll(/^CREATE TRIGGER (\w+)/gm)].map(m => m[1]));
}
supplemental = supplemental.trimEnd() + "\n";
const tables = [...sql.matchAll(/^CREATE TABLE ("(?:[^"]+)"(?:\."[^"]+")?)/gm)].map(m => m[1]);
const acl =
  "-- Reset only tables explicitly generated by this prototype, never managed Supabase objects.\nREVOKE ALL ON TABLE " +
  tables.join(",") +
  " FROM PUBLIC,anon,authenticated,mnweb;\n";
writeFileSync(resolve(here, "bootstrap-reset-access.sql"), acl);
const tableOids = tables.map(t => "'" + t + "'::regclass").join(",");
const functionNames = manifest.functions.map(n => "'" + n + "'").join(",");
const audit = `-- Fail closed on unreviewed default/direct grants; inherited role membership is a provisioning gate.
DO $$ BEGIN
 IF EXISTS(SELECT 1 FROM pg_class c,LATERAL aclexplode(coalesce(c.relacl,acldefault('r',c.relowner))) a
 WHERE c.oid IN (${tableOids}) AND a.grantee NOT IN (c.relowner,(SELECT oid FROM pg_roles WHERE rolname='mnweb')))
 OR EXISTS(SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace,
 LATERAL aclexplode(coalesce(p.proacl,acldefault('f',p.proowner))) a
 WHERE n.nspname||'.'||p.proname IN (${functionNames}) AND (a.grantee NOT IN (p.proowner,(SELECT oid FROM pg_roles WHERE rolname='mnweb')) OR (p.prosecdef AND a.grantee<>p.proowner AND p.oid<>'mn_private.lock_lore_activity_events(uuid)'::regprocedure)))
 THEN RAISE EXCEPTION 'Unexpected prototype object grants'; END IF;
END $$;
`;
writeFileSync(resolve(here, "bootstrap-audit.sql"), audit);
writeFileSync(resolve(here, "fresh-schema.bootstrap.sql"), sql);
writeFileSync(resolve(here, "bootstrap-functions.sql"), supplemental);
writeFileSync(
  resolve(here, "bootstrap-manifest.json"),
  JSON.stringify(
    { ...manifest, baselineSha256: hash(sql), functionsSha256: hash(supplemental) },
    null,
    2,
  ) + "\n",
);
